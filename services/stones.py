def stone_of_day(when: datetime | None = None) -> dict[str, Any]:
    day = (when or datetime.utcnow()).timetuple().tm_yday
    return STONES[day % len(STONES)]


def random_stone(*, prefer_undiscovered: list[str] | None = None) -> dict[str, Any]:
    pool = list(STONES)
    if prefer_undiscovered:
        known = set(prefer_undiscovered)
        fresh = [s for s in pool if s["id"] not in known]
        if fresh:
            # rare stones less often
            weights = [ {"common": 8, "uncommon": 5, "rare": 3, "vrare": 2, "epic": 1, "mythic": 1}[s["rarity"]] for s in fresh]
            return random.choices(fresh, weights=weights, k=1)[0]
    weights = [{"common": 8, "uncommon": 5, "rare": 3, "vrare": 2, "epic": 1, "mythic": 1}[s["rarity"]] for s in pool]
    return random.choices(pool, weights=weights, k=1)[0]


