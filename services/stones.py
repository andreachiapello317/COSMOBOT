def museum_room(room: str) -> list[dict[str, Any]]:
    if room in CATS:
        return by_cat(room)
    if room == "old":
        return [s for s in STONES if s.get("ancient")]
    if room == "color":
        return [s for s in STONES if "multi" in s["colors"] or "change" in s["colors"]]
    if room == "sci":
        return [s for s in STONES if s.get("sci_interest")]
    return []


def _fold(text: str) -> str:
    norm = unicodedata.normalize("NFD", text.lower())
    return "".join(ch for ch in norm if unicodedata.category(ch) != "Mn")


def search_stones(query: str) -> list[dict[str, Any]]:
    q = _fold(query.strip())
    if len(q) < 2:
        return []
    hits: list[dict[str, Any]] = []
    for item in STONES:
        blob = _fold(" ".join([item["it"], item["group"], item["formula"], item["wiki"], item["wiki_it"], item["color"]]))
        if q in blob:
            hits.append(item)
    return hits


def filter_lab(answers: dict[str, Any]) -> list[dict[str, Any]]:
    rows = list(STONES)
    color = answers.get("color")
    if color:
        rows = [s for s in rows if color in s["colors"]]
    hard = answers.get("hard")
    if hard == "soft":
        rows = [s for s in rows if s["mohs_n"] < 4]
    elif hard == "mid":
        rows = [s for s in rows if 4 <= s["mohs_n"] <= 7]
    elif hard == "hard":
        rows = [s for s in rows if s["mohs_n"] > 7]
    trans = answers.get("trans")
    if trans == "yes":
        rows = [s for s in rows if "trasparente" in s["transparency"]]
    elif trans == "no":
        rows = [s for s in rows if "opac" in s["transparency"]]
    metal = answers.get("metal")
    if metal is True:
        rows = [s for s in rows if s["metallic"]]
    elif metal is False:
        rows = [s for s in rows if not s["metallic"]]
    mag = answers.get("mag")
    if mag is True:
        rows = [s for s in rows if s["magnetic"]]
    elif mag is False:
        rows = [s for s in rows if not s["magnetic"]]
    fizz = answers.get("fizz")
    if fizz is True:
        rows = [s for s in rows if s["fizz"]]
    elif fizz is False:
        rows = [s for s in rows if not s["fizz"]]
    return rows


