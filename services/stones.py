def format_list(rows: list[dict[str, Any]], title: str, blurb: str) -> str:
    lines = [f"{title}", "", blurb, ""]
    if not rows:
        lines.append("Nessuna pietra del catalogo per questo filtro.")
        return "\n".join(lines)
    for item in rows:
        rem, rname = RARITY[item["rarity"]]
        lines.append(f"{item['emoji']} <b>{item['it']}</b> · {item['formula']} · {rem} {rname}")
    lines.append(f"\n<i>{len(rows)} nel catalogo COSMOBOT. Tocca un numero o il nome sotto.</i>")
    return "\n".join(lines)


def build_guess() -> dict[str, Any] | None:
    stone = random.choice(list(STONES))
    clues = [
        f"Formula: {stone['formula']}",
        f"Durezza Mohs: {stone['mohs']}",
        f"Sistema / origine: {stone['system']} · {stone['origin']}",
    ]
    others = [s for s in STONES if s["id"] != stone["id"]]
    random.shuffle(others)
    options = [stone] + others[:3]
    random.shuffle(options)
    return {
        "kind": "guess",
        "answer": next(i for i, s in enumerate(options) if s["id"] == stone["id"]),
        "options": [s["it"] for s in options],
        "clues": clues,
        "id": stone["id"],
    }


def build_tf() -> dict[str, Any]:
    stone = random.choice(list(STONES))
    field, truth = random.choice(
        (
            ("formula", stone["formula"]),
            ("mohs", stone["mohs"]),
            ("system", stone["system"]),
            ("group", stone["group"]),
        )
    )
    lie_stone = random.choice([s for s in STONES if s["id"] != stone["id"]])
    lie = {"formula": lie_stone["formula"], "mohs": lie_stone["mohs"], "system": lie_stone["system"], "group": lie_stone["group"]}[field]
    use_truth = random.random() < 0.5
    value = truth if use_truth else lie
    labels = {"formula": "formula", "mohs": "durezza Mohs", "system": "sistema cristallino", "group": "gruppo"}
    return {
        "kind": "tf",
        "answer": 0 if use_truth else 1,
        "options": ["Vero", "Falso"],
        "prompt": f"{stone['emoji']} {stone['it']}: la sua {labels[field]} è {value}?",
        "id": stone["id"],
    }


def build_field_quiz(field: str) -> dict[str, Any] | None:
    stone = random.choice(list(STONES))
    if field == "color":
        prompt = f"Quale pietra è tipicamente {stone['color']}?"
        key = "it"
        answer_val = stone["it"]
    elif field == "formula":
        prompt = f"Quale formula è di {stone['it']}?"
        key = "formula"
        answer_val = stone["formula"]
    elif field == "origin":
        prompt = f"Origine di {stone['it']}?"
        key = "origin"
        answer_val = stone["origin"]
    elif field == "history":
        prompt = f"Quale pietra ha questa storia?\n<i>{stone['history'][:180]}</i>"
        key = "it"
        answer_val = stone["it"]
    elif field == "mohs":
        prompt = f"Durezza Mohs di {stone['it']}?"
        key = "mohs"
        answer_val = stone["mohs"]
    else:
        return build_guess()
    others = [s for s in STONES if s[key] != stone[key]]
    random.shuffle(others)
    options_vals = [answer_val] + [s[key] if key != "it" else s["it"] for s in others[:3]]
    # unique
    uniq: list[str] = []
    for val in options_vals:
        if val not in uniq:
            uniq.append(val)
    while len(uniq) < 4:
        extra = random.choice(STONES)
        cand = extra[key] if key != "it" else extra["it"]
        if cand not in uniq:
            uniq.append(cand)
    random.shuffle(uniq)
    return {
        "kind": field,
        "answer": uniq.index(answer_val),
        "options": uniq[:4],
        "prompt": prompt,
        "id": stone["id"],
    }


